/**
 * Return master seed hits dynamically stamped relative to current real time
 */
export function getMasterSeedHits(): LiveConsoleHit[] {
  const now = Date.now();
  return MASTER_SEED_HITS_DEF.map((hit, index) => {
    const timeMs = now - hit.ageMinutesAgo * 60 * 1000 - index * 2500;
    const d = new Date(timeMs);
    const dtStr = d.toISOString().replace("T", " ").substring(0, 19);

    return {
      id: `master_seed_${hit.sid.toLowerCase()}_${hit.range}_${index}`,
      range: hit.range,
      number: hit.number,
      num: hit.number,
      sid: hit.sid,
      service: hit.service,
      cli: hit.cli,
      message: hit.message,
      code: hit.code,
      otp: hit.otp,
      payout: hit.payout,
      operator: hit.operator,
      country: hit.country,
      time: timeMs,
      dt: dtStr,
      source: hit.source,
      isFoxSms: hit.isFoxSms ?? false,
    };
  });
}

